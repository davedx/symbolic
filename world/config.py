"""World configuration (loaded from YAML; every field has a default)."""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass, field, fields, is_dataclass
from pathlib import Path

import yaml


@dataclass
class TaxonomyConfig:
    target_categories: int = 50
    tolerance: int = 6  # accept trees with target +/- tolerance categories
    n_top: int = 2  # number of level-1 categories (the implicit root is not a category)
    max_depth: int = 5  # deepest level a category can sit at
    min_leaf_depth: int = 3  # no leaf shallower than this
    branching: tuple[int, int] = (2, 3)  # children per internal node, inclusive
    p_leaf: float = 0.5  # P(node is a leaf) for min_leaf_depth <= level < max_depth
    min_entities_per_leaf: int = 5


@dataclass
class PropertyConfig:
    n_inherited_bool: int = 70  # boolean properties attached to categories and inherited
    n_categorical: int = 10  # categorical attributes attached to categories and inherited
    categorical_values: tuple[int, int] = (3, 5)  # values per categorical attribute, inclusive
    n_individual: int = 20  # boolean properties stated only on individual entities
    individual_per_entity: int = 3  # individual-property facts per entity
    attachments: tuple[int, int] = (1, 3)  # disjoint attachment points per inherited property
    category_exception_rate: float = 0.10  # P(a descendant category overrides an inherited value)
    entity_exception_rate: float = 0.05  # P(an entity overrides an inherited value)


@dataclass
class RelationConfig:
    n_functional: int = 6  # plain functional relations: every entity has exactly one object
    n_symmetric: int = 1  # symmetric functional relations (a perfect matching)
    n_inverse_pairs: int = 1  # pairs (r, r_inv) where r is a permutation
    n_transitive: int = 1  # strict orders generated by a forest of direct links
    transitive_group_size: int = 25  # entities per tree of the transitive forest
    transitive_window: int = 3  # a new node attaches to one of the last `window` nodes (=> deep trees)


@dataclass
class QueryConfig:
    max_hops: int = 6  # queries with more hops are discarded
    chain_per_hop: int = 2000  # sampled relation-composition queries per hop count
    trans_per_hop: int = 1000  # sampled positive transitive queries per hop count (+ as many negatives)
    isa_negatives_per_level: int = 1
    max_per_stratum: int = 5000  # cap per (form, task_type, hops) stratum; 0 = no cap


@dataclass
class SplitConfig:
    train_max_hops: int = 3
    length_hops: tuple[int, int] = (4, 6)  # inclusive hop range of test_length
    iid_fraction: float = 0.1  # of the remaining pool, fraction sent to test_iid
    combo_entity_fraction: float = 0.2  # held-out grid: fraction of entities ...
    combo_predicate_fraction: float = 0.3  # ... x fraction of predicates (properties + relations)
    heldout_category_level: int = 2
    n_heldout_category_relations: int = 3  # (category, relation) pairs never queried in train
    n_heldout_category_properties: int = 5  # (category, property) pairs never queried in train


@dataclass
class WorldConfig:
    seed: int = 0
    n_entities: int = 1000
    taxonomy: TaxonomyConfig = field(default_factory=TaxonomyConfig)
    properties: PropertyConfig = field(default_factory=PropertyConfig)
    relations: RelationConfig = field(default_factory=RelationConfig)
    queries: QueryConfig = field(default_factory=QueryConfig)
    splits: SplitConfig = field(default_factory=SplitConfig)

    def to_dict(self) -> dict:
        return asdict(self)

    def fingerprint(self) -> str:
        blob = json.dumps(self.to_dict(), sort_keys=True, default=list)
        return hashlib.sha256(blob.encode()).hexdigest()[:12]

    @classmethod
    def from_dict(cls, d: dict | None) -> "WorldConfig":
        return _build(cls, d or {})

    @classmethod
    def from_yaml(cls, path: str | Path) -> "WorldConfig":
        return cls.from_dict(yaml.safe_load(Path(path).read_text()))


def _build(cls, d: dict):
    known = {f.name: f for f in fields(cls)}
    unknown = set(d) - set(known)
    if unknown:
        raise ValueError(f"unknown keys for {cls.__name__}: {sorted(unknown)}")
    kwargs = {}
    defaults = cls()
    for name, value in d.items():
        default = getattr(defaults, name)
        if is_dataclass(default):
            kwargs[name] = _build(type(default), value or {})
        elif isinstance(default, tuple):
            kwargs[name] = tuple(value)
        else:
            kwargs[name] = value
    return cls(**kwargs)
